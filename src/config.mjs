/**
 * config.mjs — load, validate and normalize `sfdx-pipeline.config.yml`.
 *
 * The config file is the single source of truth: GitHub Actions, the local CLI
 * and the Claude Code skills all read it. Validation is therefore strict and
 * loud — a typo in a test level or a threshold must fail at `validate` time,
 * not halfway through a deployment.
 *
 * Every error carries the YAML path it came from (`pipeline_settings.unit_test.
 * test_level`) so the message points at the line to edit.
 */

import fs from "node:fs";
import path from "node:path";
// js-yaml v5 is ESM with named exports only — there is no default export.
import { load as parseYaml } from "js-yaml";

